-- Pending team decisions: supported event types, account/track deletion policy,
-- and client occurrence-time validation. Do not claim CC6.1 is enforced by this DDL.

CREATE TABLE playback_events (
    id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,

    -- Stable UUID supplied for each logical client event; retries reuse this value.
    client_event_id UUID NOT NULL,

    -- The API must derive user_id from its authenticated principal, not request body.
    user_id BIGINT NOT NULL
        REFERENCES users(id)
        ON DELETE RESTRICT,

    track_id BIGINT NOT NULL
        REFERENCES tracks(id)
        ON DELETE RESTRICT,

    -- Event names are not enumerated until the team approves the event contract.
    event_type TEXT NOT NULL
        CHECK (char_length(trim(event_type)) > 0),

    -- Client occurrence time enables later offline-event reconciliation.
    occurred_at TIMESTAMPTZ NOT NULL,

    -- Trusted server-side receipt time (not supplied by the client).
    received_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),

    CONSTRAINT playback_events_user_client_event_unique
        UNIQUE (user_id, client_event_id)
);

-- User-scoped chronological history retrieval.
CREATE INDEX playback_events_user_chronology_idx
    ON playback_events(user_id, occurred_at DESC, id DESC);

-- Supports track-reference lookups and future deletion-policy checks.
CREATE INDEX playback_events_track_id_idx
    ON playback_events(track_id);
